// Music cue sheet: every cue the adaptive system can play — state, theme, tempo, key,
// sections, loop length and points, stems — generated from src/audio/music/.
// Usage: node scripts/music-cue-sheet.mjs [out.md]   (default docs/audio/music-cues.md)
import { writeFileSync } from 'node:fs';
import { importTs } from './lib/ts-import.mjs';

const out = process.argv[2] ?? 'docs/audio/music-cues.md';
const { THEMES, LAYERS, loopSeconds, MODES } = await importTs('src/audio/music/themes.ts');
const { MUSIC_STATES, themeFor } = await importTs('src/audio/music/state.ts');

const NOTE = ['C', 'C♯', 'D', 'E♭', 'E', 'F', 'F♯', 'G', 'A♭', 'A', 'B♭', 'B'];
const modeName = (m) => Object.entries(MODES).find(([, v]) => v.join() === m.join())?.[0] ?? 'custom';
const mmss = (s) => `${Math.floor(s / 60)}:${String(Math.round(s % 60)).padStart(2, '0')}`;

const usedBy = {};
for (const st of MUSIC_STATES)
  for (const ctx of [{}, { chapter: 2 }, { chapter: 3 }, { chapter: 4 }, { won: false }, { challenge: true }, { challenge: true, chapter: 2 }, ...['matins', 'lauds', 'prime', 'terce', 'sext', 'none', 'vespers', 'compline'].map((hour) => ({ hour })), ...['triage', 'diagnosis', 'forensic', 'boneset'].map((discipline) => ({ discipline }))]) {
    const t = themeFor(st, ctx);
    const plain = Object.keys(ctx).length === 0;
    if (!plain && t === themeFor(st, {})) continue;
    if (t) (usedBy[t] ??= new Set()).add(st + (ctx.hour ? ` (${ctx.hour})` : ctx.discipline ? ` (${ctx.discipline})` : ctx.chapter ? ` (ch ${ctx.chapter}${ctx.challenge ? ', challenge' : ''})` : ctx.challenge ? ' (challenge)' : ctx.won === false ? ' (loss)' : ''));
  }

const lines = [
  '# Music cue sheet',
  '',
  'Generated by `node scripts/music-cue-sheet.mjs` from `src/audio/music/`. Every cue is currently rendered by the procedural score; the **Owner** column records who delivers the final stems (see `docs/handoff/AUD/`).',
  '',
  'Loop points: through-composed themes loop from bar 1 at the end of their section order (the "Loop" column); state-driven themes (bosses) loop within the section chosen by the game. All stems of a theme share one bar clock, so they are sample-aligned by construction.',
  '',
  '| Theme | Played for | Tempo | Key / mode | Sections (bars) | Loop | Intro | Stems | Owner |',
  '|---|---|---|---|---|---|---|---|---|',
];
for (const [id, t] of Object.entries(THEMES)) {
  const secs = Object.entries(t.sections).map(([k, s]) => `${k} ${s.chords.length}`).join(', ');
  const order = t.order ? `${t.order.join('→')}` : 'by game state';
  const stems = LAYERS.filter((l) => t.layers[l] || Object.values(t.sections).some((s) => s.layers?.[l])).join(', ');
  const intro = t.intro ? `${t.intro.chords.length} bars (${mmss((t.intro.chords.length * t.beats * 60) / t.bpm)})` : '—';
  const loop = t.order ? `0:00–${mmss(loopSeconds(t))}` : `per section`;
  lines.push(`| \`${id}\` | ${[...(usedBy[id] ?? ['—'])].join('; ')} | ${t.bpm} BPM, ${t.beats}/4 | ${NOTE[t.root % 12]} ${modeName(t.mode)} | ${secs} (${order}) | ${loop} | ${intro} | ${stems} | procedural; final: composer |`);
}
lines.push('', 'Stingers (in key of the playing track, on its next beat): scrub-in, phase clear, boss reveal, victory (Picardy third), failure (bowed-string scrape), rank reveal, Chapter I/II card fanfares.', '');
writeFileSync(out, lines.join('\n'));
console.log(`wrote ${Object.keys(THEMES).length} cues to ${out}`);
